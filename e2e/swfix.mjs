import { chromium } from 'playwright-core';
import { execSync, spawn } from 'node:child_process';
const [S, oldDir, newDir] = process.argv.slice(2);
const serve = (dir) => spawn('npx', ['vite', 'preview', '--outDir', dir, '--port', '4177', '--strictPort'], { cwd: process.cwd(), stdio: 'ignore', detached: true });
const exe = process.env.HOME + '/.cache/ms-playwright/chromium-1237/chrome-linux64/chrome';
execSync(`rm -rf ${S}/profile3`);
let srv = serve(oldDir); await new Promise(r => setTimeout(r, 2500));
const ctx = await chromium.launchPersistentContext(`${S}/profile3`, { executablePath: exe });
const p = await ctx.newPage();
await p.goto('http://localhost:4177/'); await p.waitForSelector('.day'); await p.waitForTimeout(3000);
process.kill(-srv.pid); await new Promise(r => setTimeout(r, 800));
srv = serve(newDir); await new Promise(r => setTimeout(r, 2500));
const errs = []; p.on('pageerror', e => errs.push(e.message));
const bundle = async () => p.evaluate(() => [...document.scripts].map(s => s.src).find(s => s.includes('index-'))?.split('/').pop());
await p.reload(); await p.waitForSelector('.day'); await p.waitForTimeout(6000);
console.log('1st load after deploy: bundle', await bundle(), '| toasts', await p.locator('.toast').count(), '| errors', errs.length);
let navs = 0; p.on('framenavigated', (f) => f === p.mainFrame() && navs++);
await p.waitForTimeout(12000);
console.log('self-reloads in next 12s:', navs);
await p.screenshot({ path: `${S}/swfix.png` });
console.log('state text:', (await p.locator('body').innerText()).slice(0, 160).replace(/\s+/g, ' '));
console.log('bundle now', await bundle().catch(() => '?'), '| toasts', await p.locator('.toast').count());
await p.reload().catch(e => console.log('reload err', e.message));
const ok = await p.waitForSelector('.day', { timeout: 20000 }).then(() => true).catch(() => false);
await p.screenshot({ path: `${S}/swfix2.png` });
console.log('after normal reload: app shown', ok, '| bundle', await bundle().catch(() => '?'), '| toasts', await p.locator('.toast').count(), '| text:', (await p.locator('body').innerText()).slice(0, 120).replace(/\s+/g, ' '));
const p2 = await ctx.newPage(); await p.close();
await p2.goto('http://localhost:4177/');
const ok2 = await p2.waitForSelector('.day', { timeout: 20000 }).then(() => true).catch(() => false);
console.log('fresh tab: app shown', ok2, '| bundle', await p2.evaluate(() => [...document.scripts].map(s => s.src).find(s => s.includes('index-'))?.split('/').pop()), '| toasts', await p2.locator('.toast').count());
await ctx.close(); process.kill(-srv.pid);
