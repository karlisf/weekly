import { chromium } from 'playwright-core';
import { execSync, spawn } from 'node:child_process';
const S = process.argv[2];
const serve = (dir) => spawn('npx', ['vite', 'preview', '--outDir', dir, '--port', '4175', '--strictPort'], { cwd: process.cwd(), stdio: 'ignore' });
const exe = process.env.HOME + '/.cache/ms-playwright/chromium-1237/chrome-linux64/chrome';
execSync(`rm -rf ${S}/profile`);
let srv = serve(`${S}/dist-old`); await new Promise(r => setTimeout(r, 2500));
let ctx = await chromium.launchPersistentContext(`${S}/profile`, { executablePath: exe, serviceWorkers: 'block' });
let p = await ctx.newPage();
await p.goto('http://localhost:4175/'); await p.waitForSelector('.day'); await p.waitForTimeout(500);
await p.locator('.day.today .add').click(); await p.keyboard.type('Made in v1'); await p.keyboard.press('Enter'); await p.keyboard.press('Escape');
await p.waitForTimeout(500);
const before = (await p.locator('.title').allTextContents()).sort();
await ctx.close(); srv.kill(); await new Promise(r => setTimeout(r, 1000));
srv = serve(`${S}/dist-new`); await new Promise(r => setTimeout(r, 2500));
ctx = await chromium.launchPersistentContext(`${S}/profile`, { executablePath: exe, serviceWorkers: 'block' });
p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:4175/'); await p.waitForSelector('.day', { timeout: 15000 }); await p.waitForTimeout(800);
const after = (await p.locator('.title').allTextContents()).sort();
console.log('same tasks after upgrade:', JSON.stringify(before) === JSON.stringify(after), after.length);
console.log('sync button present:', await p.locator('.sync-btn').count());
console.log('errors:', errs.length ? errs : 'none');
await ctx.close(); srv.kill();
